"""Generate the exhaustive design-property matrix from runtime validation."""
from pathlib import Path
import sys
ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0,str(ROOT))
from ucl.design import STYLE_KEYS, ENUMS, COLOR_KEYS, NATIVE_KEYS, TUI_KEYS


def markdown():
    text = '# Complete style property matrix (0.4)\n\nGenerated by `python tools/generate_design.py`. All keys work in browser records. Unsupported native/TUI keys raise errors. For arbitrary CSS features beyond these record conveniences, use compiled [Tailwind/CSS stylesheets](../design.md).\n\n'
    text += 'Colors: supported portable names or `#RRGGBB`; `transparent` is browser-only. Token strings (`"$primary"`) resolve before validation. Integer ranges below are inclusive. Dimensions are pixels unless noted; `font_size` is points, `width` is ch/native character units (native panels use pixels).\n\n'
    text += '| Key | Values | Native GUI | TUI |\n| --- | --- | --- | --- |\n'
    for key in sorted(STYLE_KEYS):
        if key in ENUMS: values = ', '.join('`'+v+'`' for v in sorted(ENUMS[key]))
        elif key in COLOR_KEYS: values = 'Color'
        elif key == 'font_family': values = 'Validated family name/list (letters, digits, spaces, commas, hyphens, underscores; max 101 chars)'
        elif key == 'column_span': values = 'Integer 1–12'
        elif key == 'font_size': values = 'Integer 1–512 pt'
        elif key in {'duration_ms','transition_ms'}: values = 'Integer 0–60000 ms'
        elif key == 'opacity': values = 'Number 0–1'
        elif key == 'scale': values = 'Number 0–10'
        elif key in {'top','right','bottom','left','z_index','rotate','translate_x','translate_y','letter_spacing'}: values = 'Integer -4096–4096 (rotate: degrees; z_index: unitless)'
        else: values = 'Integer 0–4096 (grow/shrink: unitless)'
        text += f'| `{key}` | {values} | {"Yes" if key in NATIVE_KEYS else "No"} | {"Yes" if key in TUI_KEYS else "No"} |\n'
    text += '\n## Native widget details\n\nPadding applies inside labels/buttons/panels; input/checkbox spacing should use margin. Height is unsupported on single-line inputs; it uses widget-native units elsewhere. Panel alignment positions its legend. Window defaults inherit to controls; avoid control-specific dimensions on window style. A property being supported does not promise pixel-perfect parity.\n\nNative animation interpolates existing integer/hex color values; CSS animation presets/easing/transform properties are browser-only. TUI spacing is cell-based; it supports only the keys marked above. See [design guide](../design.md) for states, responsive breakpoints, tokens, precedence, reduced motion and security.\n'
    return text

if __name__ == '__main__':
    target = ROOT/'docs/reference/styles.md'
    target.write_text(markdown(),encoding='utf-8')
    print(target)
